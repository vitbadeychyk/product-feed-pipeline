# Якщо для нової категорії запис у CATEGORY_PARAMS ще не створили,
# тимчасово зберігаємо стару поведінку.
DEFAULT_CATEGORY_PARAMS: tuple[str, ...] = (
    "Матеріал",
    "Гарантія",
)


def get_category_params(
    category_id: str,
) -> tuple[str, ...]:
    category_id = str(
        category_id or ""
    ).strip()

    return CATEGORY_PARAMS.get(
        category_id,
        DEFAULT_CATEGORY_PARAMS,
    )


def get_parameter_config(
    parameter_name: str,
) -> dict[str, object]:
    return PARAMETER_CONFIG.get(
        parameter_name,
        {
            "source_names": (
                parameter_name,
            ),
        },
    )
