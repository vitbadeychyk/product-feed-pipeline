def get_eva_category_id(supplier_category_id: str) -> str | None:
    category_id = str(supplier_category_id or "").strip()
    return EVA_CATEGORY_MAP.get(category_id)


def is_ignored_category(supplier_category_id: str) -> bool:
    return str(supplier_category_id or "").strip() in EVA_IGNORED_CATEGORY_IDS
